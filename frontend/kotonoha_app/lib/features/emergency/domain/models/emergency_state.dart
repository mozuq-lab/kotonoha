/// 緊急状態列挙型
/// 緊急呼び出し機能の状態を表す列挙型。
/// アプリケーション全体で緊急状態を追跡するために使用。
library;

/// 緊急呼び出し機能の状態
/// 画面に何を出すかの状態で、音が実際に鳴っているかは表さない。音声は
/// 状態の後から追いかける（視覚が先。台帳 L-110）
/// normal: 通常状態（緊急画面なし）
/// alertActive: 緊急呼び出し中（緊急画面あり）
/// resetting: リセット処理中（将来の拡張用）
enum EmergencyStateEnum {
  /// 通常状態
  /// 緊急画面を出していない状態。リセットの直後は、音の停止がまだ
  /// 終わっていないことがある。
  /// アプリ起動時の初期状態。
  normal,

  /// 緊急呼び出し中
  /// 画面が赤く表示されている状態。緊急音はこの後から鳴り始め、再生に
  /// 失敗しても画面は出したままにする。
  /// リセットボタンタップまで継続。
  alertActive,

  /// リセット処理中（将来の拡張用）
  /// リセットボタンタップ後の処理中状態。
  /// 現時点では使用しない。
  resetting,
}
